/**
 * Reconstructs CREATE statements for the table info panel, and formats stats.
 *
 * Postgres has no `pg_get_tabledef()`, so this assembles one from catalog
 * pieces that Postgres *does* render authoritatively: format_type,
 * pg_get_expr (defaults/generated), pg_get_constraintdef, pg_get_indexdef,
 * pg_get_viewdef, pg_get_partkeydef and pg_get_triggerdef. The result is the
 * shape `pg_dump --schema-only` would print for the table, but without
 * ownership, grants, storage parameters or sequences.
 *
 * Pure (catalog rows in, text out), so it is unit-tested.
 */
import { qualifiedTable, quoteIdent } from './changesetSql'

export interface DdlColumn {
  name: string
  type: string
  notNull: boolean
  defaultExpr: string | null
  /** pg_attribute.attidentity: '' | 'a' (ALWAYS) | 'd' (BY DEFAULT). */
  identity: string
  /** pg_attribute.attgenerated: '' | 's' (STORED) | 'v' (VIRTUAL, PG18+). */
  generated: string
  comment: string | null
}

export interface DdlInput {
  schema: string
  table: string
  /** pg_class.relkind: r table, p partitioned, v view, m matview, f foreign. */
  relkind: string
  columns: DdlColumn[]
  /** Table constraints (not NOT NULL) as `CONSTRAINT name <def>`. */
  constraints: Array<{ name: string; def: string }>
  /** Indexes that do NOT back a PK/UNIQUE/EXCLUDE constraint (those are in `constraints`). */
  standaloneIndexes: string[]
  triggers: string[]
  comment: string | null
  viewDef: string | null
  partitionKey: string | null
  partitionOf: { parent: string; bound: string } | null
}

export const quoteLiteral = (s: string): string => `'${s.replace(/'/g, "''")}'`

function columnLine(c: DdlColumn): string {
  const parts = [`  ${quoteIdent(c.name)} ${c.type}`]
  if (c.identity === 'a') parts.push('GENERATED ALWAYS AS IDENTITY')
  else if (c.identity === 'd') parts.push('GENERATED BY DEFAULT AS IDENTITY')
  else if (c.generated && c.defaultExpr) parts.push(`GENERATED ALWAYS AS (${c.defaultExpr}) ${c.generated === 'v' ? 'VIRTUAL' : 'STORED'}`)
  else if (c.defaultExpr) parts.push(`DEFAULT ${c.defaultExpr}`)
  if (c.notNull) parts.push('NOT NULL')
  return parts.join(' ')
}

export function buildTableDdl(d: DdlInput): string {
  const name = qualifiedTable(d.schema, d.table)
  const out: string[] = []

  if (d.relkind === 'v' || d.relkind === 'm') {
    const body = (d.viewDef ?? '').trim().replace(/;+$/, '')
    out.push(`CREATE ${d.relkind === 'm' ? 'MATERIALIZED VIEW' : 'VIEW'} ${name} AS\n${body};`)
  } else if (d.partitionOf) {
    out.push(`CREATE TABLE ${name} PARTITION OF ${d.partitionOf.parent}\n  ${d.partitionOf.bound};`)
  } else {
    const lines = [...d.columns.map(columnLine), ...d.constraints.map((c) => `  CONSTRAINT ${quoteIdent(c.name)} ${c.def}`)]
    const partition = d.partitionKey ? `\nPARTITION BY ${d.partitionKey}` : ''
    out.push(`CREATE ${d.relkind === 'f' ? 'FOREIGN TABLE' : 'TABLE'} ${name} (\n${lines.join(',\n')}\n)${partition};`)
  }

  for (const idx of d.standaloneIndexes) out.push(`${idx};`)
  if (d.comment) out.push(`COMMENT ON ${d.relkind === 'v' ? 'VIEW' : d.relkind === 'm' ? 'MATERIALIZED VIEW' : 'TABLE'} ${name} IS ${quoteLiteral(d.comment)};`)
  for (const c of d.columns) {
    if (c.comment) out.push(`COMMENT ON COLUMN ${name}.${quoteIdent(c.name)} IS ${quoteLiteral(c.comment)};`)
  }
  for (const t of d.triggers) out.push(`${t};`)
  return out.join('\n\n')
}

/** 1536 → "1.5 kB". Binary units, like pg_size_pretty. */
export function formatBytes(n: number | null): string {
  if (n === null || !Number.isFinite(n)) return '–'
  const units = ['bytes', 'kB', 'MB', 'GB', 'TB']
  let v = n
  let i = 0
  while (v >= 1024 && i < units.length - 1) {
    v /= 1024
    i++
  }
  return i === 0 ? `${v} bytes` : `${v.toFixed(v < 10 ? 1 : 0)} ${units[i]}`
}

export function formatCount(n: number | null): string {
  return n === null || !Number.isFinite(n) ? '–' : n.toLocaleString('en-US')
}
