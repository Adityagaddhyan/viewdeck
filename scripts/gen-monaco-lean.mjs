#!/usr/bin/env node
// Regenerates src/renderer/src/features/editor/monacoLean.ts from the installed
// monaco-editor's editor.main.js, dropping every `languages/*` import (TS/CSS/
// HTML/JSON workers, ~15 MB) and registering only the pgsql grammar.
// Run after upgrading monaco-editor:  npm run gen:monaco && npm run test:e2e
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..')
const main = readFileSync(join(root, 'node_modules/monaco-editor/esm/vs/editor/editor.main.js'), 'utf8')

const specs = []
for (const [, path] of main.matchAll(/^import '([^']+)';$/gm)) {
  if (path.includes('/languages/')) continue
  let spec
  if (path.startsWith('./')) spec = `@monaco-esm/editor/${path.slice(2)}`
  else if (path.startsWith('../')) spec = `@monaco-esm/${path.slice(3)}`
  else continue
  if (!specs.includes(spec)) specs.push(spec)
}

const out = [
  '/**',
  ' * Lean Monaco entry. GENERATED by scripts/gen-monaco-lean.mjs (npm run gen:monaco).',
  ' * Do not edit by hand.',
  ' *',
  ' * Source: monaco-editor/esm/vs/editor/editor.main.js with every `languages/*` import',
  ' * removed, which drops ~15 MB of TS/CSS/HTML/JSON language workers that SQL never',
  ' * uses. Only the pgsql grammar is registered.',
  ' *',
  ' * `@monaco-esm` aliases node_modules/monaco-editor/esm/vs (electron.vite.config.ts),',
  ' * because the package `exports` map cannot resolve .css files.',
  ' */',
  '// @ts-nocheck: side-effect imports of Monaco internals have no type declarations.',
  '',
  ...specs.map((s) => `import '${s}'`),
  "import '@monaco-esm/languages/definitions/pgsql/register.js'",
  "export * from '@monaco-esm/editor/editor.api.js'",
  ''
]
writeFileSync(join(root, 'src/renderer/src/features/editor/monacoLean.ts'), out.join('\n'))
console.log(`monacoLean.ts: ${specs.length} editor imports + pgsql`)
